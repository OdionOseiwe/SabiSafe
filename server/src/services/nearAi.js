import { env } from "../config/env.js";
import { logger } from "../utils/logger.js";

// NEAR AI Cloud — private, attested inference.
// The SDK is imported lazily so the app still boots (with the curated guide
// fallback) on a machine where the SDK cannot load.

let chatClient = null;
let attestationClient = null;
let loadError = null;

export class NearAiError extends Error {
  constructor(code, message) {
    super(message);
    this.name = "NearAiError";
    this.code = code;
  }
}

export function isNearAiConfigured() {
  return Boolean(env.nearAi.apiKey);
}

async function sdk() {
  if (loadError) throw loadError;
  try {
    return await import("@nearai/inference-sdk/node");
  } catch (error) {
    loadError = new NearAiError(
      "sdk_unavailable",
      "The NEAR AI SDK could not be loaded. Check that npm install completed on Node 24.22.1 or newer.",
    );
    logger.error("NEAR AI SDK failed to load", { reason: error?.message });
    throw loadError;
  }
}

async function getChatClient() {
  if (chatClient) return chatClient;
  const { InferenceClient } = await sdk();
  chatClient = new InferenceClient({
    baseUrl: env.nearAi.baseUrl,
    apiKey: env.nearAi.apiKey,
    e2ee: env.nearAi.e2ee,
    signingAlgo: env.nearAi.signingAlgo,
    attestationCacheTimeToLiveMs: 60 * 60 * 1000,
  });
  return chatClient;
}

async function getAttestationClient() {
  if (attestationClient) return attestationClient;
  const { AttestationClient } = await sdk();
  attestationClient = new AttestationClient({
    baseUrl: env.nearAi.baseUrl,
    apiKey: env.nearAi.apiKey,
  });
  return attestationClient;
}

function shortAddress(value) {
  if (!value || typeof value !== "string") return null;
  return value.length > 18 ? `${value.slice(0, 10)}…${value.slice(-6)}` : value;
}

function pickSigner(source) {
  const attestation = source?.attestation || source?.report || source;
  return (
    attestation?.signing_address ||
    attestation?.signingAddress ||
    attestation?.signer?.signingAddress ||
    source?.signer?.signingAddress ||
    null
  );
}

/**
 * Verify the complete NEAR AI Cloud chain of evidence for this model:
 * Gateway attestation, model TEE attestation, and the TLS binding between them.
 * A fresh random nonce is generated by the SDK for the request.
 */
export async function verifyNearAiAttestation({ force = false } = {}) {
  if (!isNearAiConfigured()) {
    return {
      available: false,
      verified: false,
      reason: "not_configured",
      message:
        "NEAR AI is not configured on this server yet. Add NEAR_AI_API_KEY to enable private, verified answers.",
    };
  }

  const now = Date.now();
  if (!force && attestationCache && now - attestationCache.checkedAtMs < 5 * 60 * 1000) {
    return attestationCache.value;
  }

  const { verifyGatewayAttestation, verifyModelAttestation } = await sdk();
  const client = await getAttestationClient();

  const fetchedGateway = await client.fetchGatewayAttestation({ signingAlgo: env.nearAi.signingAlgo });
  const gateway = await verifyGatewayAttestation({
    attestation: fetchedGateway.attestation,
    clientBinding: fetchedGateway.clientBinding,
  });

  const fetchedModels = await client.fetchModelAttestations({
    model: env.nearAi.model,
    signingAlgo: env.nearAi.signingAlgo,
  });
  if (!fetchedModels.attestations.length) {
    throw new NearAiError("no_model_attestation", "NEAR AI returned no model attestation for this model.");
  }
  const models = await Promise.all(
    fetchedModels.attestations.map((attestation) =>
      verifyModelAttestation({
        attestation,
        clientBinding: fetchedModels.clientBinding,
      }),
    ),
  );

  const tlsKind = gateway?.tlsBinding?.kind || "none";
  const nonce = fetchedGateway.clientBinding?.nonce || fetchedModels.clientBinding?.nonce || null;

  const value = {
    available: true,
    verified: true,
    provider: "NEAR AI Cloud",
    model: env.nearAi.model,
    modelLabel: "GLM 5.3 Flash",
    privacyTier: "Confidential TEE",
    e2ee: env.nearAi.e2ee,
    checkedAt: new Date().toISOString(),
    nonce: nonce ? shortAddress(nonce) : null,
    nonceLength: nonce ? String(nonce).replace(/^0x/, "").length : null,
    gatewaySigner: shortAddress(pickSigner(gateway)),
    modelSigner: shortAddress(pickSigner(models[0])),
    tlsBinding: tlsKind,
    modelAttestations: models.length,
    checks: [
      {
        key: "fresh_nonce",
        label: "Fresh challenge matched",
        passed: Boolean(nonce),
        detail: "The SDK generated a new random challenge for this check and NEAR AI echoed it back inside the signed evidence.",
      },
      {
        key: "gateway_attestation",
        label: "NEAR AI Cloud gateway proof",
        passed: true,
        detail: "The gateway is running inside an Intel TDX trusted execution environment.",
      },
      {
        key: "model_attestation",
        label: "Model TEE proof",
        passed: true,
        detail: "The model that answered is running inside a confidential GPU environment with a valid hardware quote.",
      },
      {
        key: "tls_binding",
        label: "Secure connection binding",
        passed: tlsKind === "attested",
        detail:
          tlsKind === "attested"
            ? "The TLS connection to NEAR AI is pinned to the attested gateway key."
            : "The connection was verified without an attested TLS fingerprint.",
      },
      {
        key: "e2ee",
        label: "End-to-end encryption",
        passed: env.nearAi.e2ee,
        detail: "The prompt and answer are encrypted to the model's attested key.",
      },
    ],
    note: "This proves where the answer was processed. It does not prove the answer is factually correct, and it is not financial advice.",
  };

  attestationCache = { checkedAtMs: now, value };
  return value;
}

let attestationCache = null;

function summariseResponseVerification(model, verified) {
  const signatureKind = verified?.signatureKind || null;
  return {
    available: true,
    verified: Boolean(signatureKind),
    provider: "NEAR AI Cloud",
    model,
    modelLabel: "GLM 5.3 Flash",
    privacyTier: "Confidential TEE",
    e2ee: env.nearAi.e2ee,
    signatureKind,
    checkedAt: new Date().toISOString(),
    checks: [
      {
        key: "gateway_attestation",
        label: "Approved NEAR AI gateway",
        passed: true,
        detail: "The request was sent only after the gateway's TEE proof passed verification.",
      },
      {
        key: "model_attestation",
        label: "Private model TEE",
        passed: true,
        detail: "The SDK selected a routing key from verified model attestations before sending.",
      },
      {
        key: "e2ee",
        label: "End-to-end encryption",
        passed: env.nearAi.e2ee,
        detail: "The prompt was encrypted to the model's attested key.",
      },
      {
        key: "response_signature",
        label: "Answer signature verified",
        passed: Boolean(signatureKind),
        detail:
          signatureKind === "provider_tee"
            ? "The exact answer bytes carry a signature from the model TEE."
            : signatureKind === "gateway"
              ? "The exact answer bytes carry a signature from the NEAR AI gateway TEE."
              : "No response signature was returned.",
      },
    ],
    note: "SabiSafe checked the cryptography before showing this answer. That proves where it ran, not that it is correct. Not financial advice.",
  };
}

/**
 * Ask a private NEAR AI model and verify the response receipt before returning.
 * Throws NearAiError when the provider is unavailable or proof cannot be checked.
 */
export async function chatWithNearAi({ messages, maxTokens }) {
  if (!isNearAiConfigured()) {
    throw new NearAiError("not_configured", "NEAR AI is not configured on this server.");
  }

  const client = await getChatClient();
  const started = Date.now();

  let completion;
  try {
    completion = await client.chat.completions.create({
      model: env.nearAi.model,
      messages,
      max_tokens: maxTokens || env.nearAi.maxOutputTokens,
      temperature: 0.35,
    });
  } catch (error) {
    logger.warn("NEAR AI chat failed", { reason: error?.message, code: error?.code });
    throw new NearAiError("inference_failed", "NEAR AI could not answer that question right now.");
  }

  const content = completion?.choices?.[0]?.message?.content;
  if (!content || typeof content !== "string") {
    throw new NearAiError("empty_response", "NEAR AI returned an empty answer.");
  }

  let verification = {
    available: true,
    verified: false,
    provider: "NEAR AI Cloud",
    model: env.nearAi.model,
    modelLabel: "GLM 5.3 Flash",
    privacyTier: "Confidential TEE",
    e2ee: env.nearAi.e2ee,
    signatureKind: null,
    checkedAt: new Date().toISOString(),
    checks: [
      {
        key: "verification_skipped",
        label: "Response signature not checked",
        passed: false,
        detail: "Response verification is disabled in this environment.",
      },
    ],
    note: "The answer came from NEAR AI Cloud, but the response signature was not checked.",
  };

  if (env.nearAi.verifyResponses) {
    try {
      const verified = await client.verifyResponse(completion.id);
      verification = summariseResponseVerification(env.nearAi.model, verified);
    } catch (error) {
      logger.warn("NEAR AI response verification failed", { reason: error?.message });
      throw new NearAiError(
        "verification_failed",
        "NEAR AI answered, but we could not verify the answer's digital signature, so we will not present it as verified.",
      );
    }
  }

  return {
    content: content.trim(),
    completionId: completion.id,
    model: env.nearAi.model,
    verification,
    latencyMs: Date.now() - started,
  };
}
